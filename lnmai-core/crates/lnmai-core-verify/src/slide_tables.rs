//! Finite scalar slide tables shared with the runtime.
//! Exact string classification (including stripping ONE mirror prefix) and
//! rational construction are runtime adapters. Unknown includes every string
//! outside the listed keys; Line2/Line8 intentionally have no scalar entries.

#[derive(Debug, Clone, Copy)]
pub enum TableKey {
    Circle1,
    Circle2,
    Circle3,
    Circle4,
    Circle5,
    Circle6,
    Circle7,
    Circle8,
    Line2,
    Line3,
    Line4,
    Line5,
    Line6,
    Line7,
    Line8,
    V1,
    V2,
    V3,
    V4,
    V6,
    V7,
    V8,
    Ppqq1,
    Ppqq2,
    Ppqq3,
    Ppqq4,
    Ppqq5,
    Ppqq6,
    Ppqq7,
    Ppqq8,
    Pq1,
    Pq2,
    Pq3,
    Pq4,
    Pq5,
    Pq6,
    Pq7,
    Pq8,
    L2,
    L3,
    L4,
    L5,
    S,
    Wifi,
    Unknown,
}

/// Visual path weights, distinct from judge-queue lengths.
pub fn slide_bar_count(key: TableKey) -> Option<usize> {
    match key {
        TableKey::Circle1 => Some(64),
        TableKey::Circle2 => Some(8),
        TableKey::Circle3 => Some(16),
        TableKey::Circle4 => Some(24),
        TableKey::Circle5 => Some(32),
        TableKey::Circle6 => Some(40),
        TableKey::Circle7 => Some(48),
        TableKey::Circle8 => Some(56),
        TableKey::Line3 => Some(14),
        TableKey::Line4 => Some(19),
        TableKey::Line5 => Some(20),
        TableKey::Line6 => Some(19),
        TableKey::Line7 => Some(14),
        TableKey::V1 => Some(21),
        TableKey::V2 | TableKey::V3 | TableKey::V4 | TableKey::V6 | TableKey::V7 | TableKey::V8 => {
            Some(20)
        }
        TableKey::Ppqq1 => Some(36),
        TableKey::Ppqq2 => Some(29),
        TableKey::Ppqq3 => Some(23),
        TableKey::Ppqq4 | TableKey::Ppqq5 => Some(50),
        TableKey::Ppqq6 => Some(49),
        TableKey::Ppqq7 => Some(47),
        TableKey::Ppqq8 => Some(42),
        TableKey::Pq1 => Some(34),
        TableKey::Pq2 => Some(31),
        TableKey::Pq3 => Some(28),
        TableKey::Pq4 => Some(25),
        TableKey::Pq5 => Some(22),
        TableKey::Pq6 => Some(43),
        TableKey::Pq7 => Some(41),
        TableKey::Pq8 => Some(37),
        TableKey::L2 => Some(33),
        TableKey::L3 => Some(35),
        TableKey::L4 => Some(33),
        TableKey::L5 => Some(29),
        TableKey::S => Some(31),
        _ => None,
    }
}

