/// Advance the engine and apply the resulting core render/audio commands.
pub fn step_judge_engine(app: &mut crate::state::PlayerState) {
    if app.judge_engine.is_none() {
        return;
    }
    let t0 = Instant::now();

    app.prepare_engine_frame_events();
    let now = app.song_time();
    let events = std::mem::take(&mut app.engine_events);
    let result = app.judge_engine.as_mut().unwrap().step(now, events);
    app.finish_engine_frame();
    match result {
        Ok(result) => {
            if let Some(engine) = app.judge_engine.as_ref() {
                let updates = engine.slide_progress_updates(&result.render_commands);
                app.apply_core_slide_progress_updates(&updates);
            }
            handle_engine_result(app, result);
        }
        Err(e) => {
            if !app.status.starts_with("判引擎") {
                app.set_status(format!("engine: {e}"));
            }
        }
    }
    crate::perf::record("engine.total", t0.elapsed());
}

fn handle_engine_result(app: &mut crate::state::PlayerState, result: RuntimeStepLightResult) {
    let displays = collect_judge_result_displays(&app.chart, app.judge_engine.as_ref(), &result);
    for display in displays {
        // Slide feedback text is drawn by the slide judge band instead.
        if !display.is_slide {
            app.push_judgement(display.zone, display.label, display.duration);
        }
    }

    // Record slide judgments so the renderer can show the `just` overlay.
    let slide_results = if let Some(engine) = app.judge_engine.as_ref() {
        collect_slide_judge_results(&app.chart, Some(engine), &result)
    } else {
        Vec::new()
    };
    for slide in slide_results {
        app.record_slide_judge(
            slide.note_id,
            slide.slide_idx,
            crate::state::SlideJustKind::from_grade(slide.grade),
        );
    }

    for command in &result.audio_commands {
        play_audio_command(app, command);
    }
}

#[derive(Debug, Clone, Copy)]
struct SlideJudgeResult {
    note_id: u64,
    slide_idx: usize,
    grade: lnmai_core::types::JudgeGrade,
}

/// Map lnmai-core's runtime slide judgments onto the chart's `(note_id,
/// slide_idx)` keys used by the renderer's per-sub-slide effects.
fn collect_slide_judge_results(
    chart: &lambda_dx::app::types::ChartDoc,
    engine: Option<&JudgeEngine>,
    result: &RuntimeStepLightResult,
) -> Vec<SlideJudgeResult> {
    let mut out = Vec::new();
    let mut seen: HashSet<(u64, usize)> = HashSet::new();
    let mut push = |note_index: u64, grade: lnmai_core::types::JudgeGrade| {
        let Some(engine) = engine else { return };
        let Some(runtime_slide_index) = engine.runtime_slide_index(note_index) else {
            return;
        };
        let Some((note_id, slide_idx)) = chart_slide_key(chart, runtime_slide_index) else {
            return;
        };
        if seen.insert((note_id, slide_idx)) {
            out.push(SlideJudgeResult {
                note_id,
                slide_idx,
                grade,
            });
        }
    };

    for command in &result.render_commands {
        if let RenderCommand::ShowJudgeResult {
            kind: JudgeEventKind::Slide,
            grade,
            note_index,
            ..
        } = command
        {
            push(*note_index, *grade);
        }
    }
    for event in &result.events {
        if event.kind == JudgeEventKind::Slide {
            push(event.note_index, event.grade);
        }
    }
    out
}

#[derive(Debug, Clone, PartialEq)]
struct JudgeResultDisplay {
    zone: PadZone,
    label: &'static str,
    duration: f64,
    /// Slide feedback is rendered by the slide judge band (which draws its own
    /// direction-aligned text), so it is not pushed to the generic overlay.
    is_slide: bool,
}

fn collect_judge_result_displays(
    chart: &lambda_dx::app::types::ChartDoc,
    engine: Option<&JudgeEngine>,
    result: &RuntimeStepLightResult,
) -> Vec<JudgeResultDisplay> {
    let mut displays = Vec::new();
    let mut displayed_slide_results: HashSet<u64> = HashSet::new();
    for command in &result.render_commands {
        if let RenderCommand::ShowJudgeResult {
            kind,
            grade,
            note_index,
            ..
        } = command
        {
            if let Some(display) =
                make_judge_result_display(chart, engine, &result.events, *note_index, *kind, *grade)
            {
                if *kind == JudgeEventKind::Slide {
                    displayed_slide_results.insert(*note_index);
                }
                displays.push(display);
            }
        }
    }

    for event in &result.events {
        if event.kind == JudgeEventKind::Slide
            && !displayed_slide_results.contains(&event.note_index)
        {
            if let Some(display) = make_judge_result_display(
                chart,
                engine,
                &result.events,
                event.note_index,
                event.kind,
                event.grade,
            ) {
                displayed_slide_results.insert(event.note_index);
                displays.push(display);
            }
        }
    }

    displays
}

fn make_judge_result_display(
    chart: &lambda_dx::app::types::ChartDoc,
    engine: Option<&JudgeEngine>,
    events: &[JudgeEvent],
    note_index: u64,
    kind: JudgeEventKind,
    grade: lnmai_core::types::JudgeGrade,
) -> Option<JudgeResultDisplay> {
    let zone = judge_result_zone(chart, engine, events, note_index, kind)?;

    let label = display_label_for_grade(grade);
    let duration = if grade.is_miss_or_too_fast() {
        0.24
    } else {
        0.3
    };
    Some(JudgeResultDisplay {
        zone,
        label,
        duration,
        is_slide: kind == JudgeEventKind::Slide,
    })
}

fn judge_result_zone(
    chart: &lambda_dx::app::types::ChartDoc,
    engine: Option<&JudgeEngine>,
    events: &[JudgeEvent],
    note_index: u64,
    kind: JudgeEventKind,
) -> Option<PadZone> {
    if kind == JudgeEventKind::Slide {
        slide_tail_zone_for_runtime_note(chart, engine, note_index)
            .or_else(|| event_position_zone(events, note_index, kind))
    } else {
        event_position_zone(events, note_index, kind)
            .or_else(|| chart_note_head_zone(chart, note_index))
    }
}

fn display_label_for_grade(grade: lnmai_core::types::JudgeGrade) -> &'static str {
    if grade.is_miss_or_too_fast() {
        "Miss"
    } else if grade.is_good_grade() {
        "Good"
    } else if grade.is_great_grade() {
        "Great"
    } else {
        "Perfect"
    }
}

fn judge_sfx_allowed(grade: lnmai_core::types::JudgeGrade) -> bool {
    !grade.is_miss_or_too_fast()
}

fn event_position_zone(
    events: &[JudgeEvent],
    note_index: u64,
    kind: JudgeEventKind,
) -> Option<PadZone> {
    let ev = events
        .iter()
        .find(|ev| ev.note_index == note_index && ev.kind == kind)?;
    if let Some(button) = ev.position.button {
        Some(zone_for_button(button))
    } else {
        ev.position.sensor.map(zone_for_sensor)
    }
}

fn slide_tail_zone_for_runtime_note(
    chart: &lambda_dx::app::types::ChartDoc,
    engine: Option<&JudgeEngine>,
    note_index: u64,
) -> Option<PadZone> {
    let runtime_slide_index = engine.and_then(|engine| engine.runtime_slide_index(note_index))?;
    chart_slide_tail_zone(chart, runtime_slide_index)
}

fn chart_slide_tail_zone(
    chart: &lambda_dx::app::types::ChartDoc,
    runtime_slide_index: usize,
) -> Option<PadZone> {
    chart_slide_key(chart, runtime_slide_index).and_then(|(note_id, slide_idx)| {
        chart
            .notes
            .iter()
            .find(|note| note.id == note_id)
            .and_then(|note| note.slide.get(slide_idx))
            .and_then(|slide| slide.segments.last())
            .and_then(|segment| segment.points.last())
            .map(|point| point.zone)
    })
}

fn chart_note_head_zone(
    chart: &lambda_dx::app::types::ChartDoc,
    note_index: u64,
) -> Option<PadZone> {
    let note = chart
        .notes
        .iter()
        .find(|note| note.id == note_index)
        .or_else(|| {
            usize::try_from(note_index)
                .ok()
                .and_then(|index| chart.notes.get(index.saturating_sub(1)))
        })?;
    Some(PadZone::from(note.lane))
}

pub fn chart_slide_key(
    chart: &lambda_dx::app::types::ChartDoc,
    runtime_slide_index: usize,
) -> Option<(u64, usize)> {
    use lambda_dx::app::types::NoteType;
    let mut current = 0;
    chart
        .notes
        .iter()
        .filter(|note| matches!(note.note_type, NoteType::Slide))
        .find_map(|note| {
            for slide_idx in 0..note.slide.len() {
                if current == runtime_slide_index {
                    return Some((note.id, slide_idx));
                }
                current += 1;
            }
            None
        })
}

fn play_audio_command(app: &mut crate::state::PlayerState, command: &AudioCommand) {
    if !app.audio_enabled {
        return;
    }

    let sfx = match command {
        AudioCommand::PlayJudgeSfx {
            kind,
            grade,
            is_break,
            ..
        } => {
            if !judge_sfx_allowed(*grade) {
                return;
            }
            match kind {
                JudgeEventKind::Break => app.sfx_break_tap.as_ref(),
                JudgeEventKind::Touch => app.sfx_touch.as_ref(),
                JudgeEventKind::Slide if *is_break => app.sfx_break_slide.as_ref(),
                JudgeEventKind::Slide => app.sfx_slide.as_ref(),
                _ if *is_break => app.sfx_break_tap.as_ref(),
                _ => app.sfx_tap.as_ref(),
            }
        }
        AudioCommand::PlaySlideCue { is_break, .. } => {
            if *is_break {
                app.sfx_slide_break_start.as_ref()
            } else {
                app.sfx_slide.as_ref()
            }
        }
    };
    if let (Some(sfx), Some(player)) = (sfx, &mut app.sfx_player) {
        player.play(sfx, 1.0);
    }
}
