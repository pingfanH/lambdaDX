//! Judgment engine bridge to `lnmai-core`'s Lean FFI runtime.
//!
//! The chart is loaded into a persistent Lean runtime session; each gameplay
//! frame the player feeds a [`TimedInputBatch`] (screen sensor presses at the
//! current song time in µs) and renders the commands returned by the core. The
//! player no longer computes judge windows itself.
//!
//! Ported from the `features/pure` player's `engine.rs`, trimmed to the pad
//! preview's needs. The Lean project is discovered by `lnmai-core`'s build
//! script (see `lnmai-core/src/build.rs`): a sibling `../lnmai-core` checkout is
//! used when `LNMAI_CORE_ARTIFACTS` is not set.

use crate::app::types::zone::PadZone;
use crate::app::types::{ChartDoc, NoteType};
use crate::player::state::PadPreviewState;
use lnmai_core::session::{self, Empty, Loaded, Session};
use lnmai_core::types::{
    AudioCommand, ButtonZone, ChartSpec, GameState, JudgeEvent, JudgeEventKind, JudgeGrade,
    RenderCommand, RuntimeStepLightResult, SensorArea, TimedInputBatch, TimedInputEvent,
};
use std::collections::{HashMap, HashSet};

/// Map a pad zone to the screen sensor event family.
///
/// This frontend models only the inner screen sensor. Even A-ring contacts are
/// sent to lnmai-core as A sensors, never as K buttons. Returns
/// `(click_event, hold_down, hold_up)` for one press/release cycle.
pub fn events_for_zone(
    zone: PadZone,
    tp: i64,
) -> Option<(TimedInputEvent, TimedInputEvent, TimedInputEvent)> {
    let area = match zone.to_id() {
        1 => SensorArea::A1,
        2 => SensorArea::A2,
        3 => SensorArea::A3,
        4 => SensorArea::A4,
        5 => SensorArea::A5,
        6 => SensorArea::A6,
        7 => SensorArea::A7,
        8 => SensorArea::A8,
        9 => SensorArea::B1,
        10 => SensorArea::B2,
        11 => SensorArea::B3,
        12 => SensorArea::B4,
        13 => SensorArea::B5,
        14 => SensorArea::B6,
        15 => SensorArea::B7,
        16 => SensorArea::B8,
        17 => SensorArea::C,
        18 => SensorArea::D1,
        19 => SensorArea::D2,
        20 => SensorArea::D3,
        21 => SensorArea::D4,
        22 => SensorArea::D5,
        23 => SensorArea::D6,
        24 => SensorArea::D7,
        25 => SensorArea::D8,
        26 => SensorArea::E1,
        27 => SensorArea::E2,
        28 => SensorArea::E3,
        29 => SensorArea::E4,
        30 => SensorArea::E5,
        31 => SensorArea::E6,
        32 => SensorArea::E7,
        33 => SensorArea::E8,
        _ => return None,
    };
    Some((
        TimedInputEvent::SensorClick { tp, area },
        TimedInputEvent::SensorHold {
            tp,
            area,
            is_down: true,
        },
        TimedInputEvent::SensorHold {
            tp,
            area,
            is_down: false,
        },
    ))
}

fn press_events_from(
    events: Option<(TimedInputEvent, TimedInputEvent, TimedInputEvent)>,
) -> Vec<TimedInputEvent> {
    match events {
        Some((click, hold_down, _)) => vec![click, hold_down],
        None => Vec::new(),
    }
}

fn release_events_from(
    events: Option<(TimedInputEvent, TimedInputEvent, TimedInputEvent)>,
) -> Vec<TimedInputEvent> {
    events.map(|(_, _, hold_up)| vec![hold_up]).unwrap_or_default()
}

/// Build the sensor press generated by one active pad zone.
pub fn press_events_for_zone(zone: PadZone, tp: i64) -> Vec<TimedInputEvent> {
    press_events_from(events_for_zone(zone, tp))
}

/// Build the sensor release generated by one active pad zone.
pub fn release_events_for_zone(zone: PadZone, tp: i64) -> Vec<TimedInputEvent> {
    release_events_from(events_for_zone(zone, tp))
}

