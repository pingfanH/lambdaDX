/// A loaded lnmai-core (FFI) runtime session.
pub struct JudgeEngine {
    session: Session<Loaded>,
    chart_spec: ChartSpec,
    /// Last time successfully accepted by lnmai-core.
    ///
    /// Playback can deliver an autoplay event a frame late after a render or
    /// audio hitch. The core rejects a batch whose clock moves backwards, so
    /// we retain its clock here and retime only events that arrived behind it.
    last_step_time_us: i64,
    slide_bindings: HashMap<u64, usize>,
    /// Core slide head timings (µs), indexed by runtime slide index.
    slide_head_timings: Vec<i64>,
    /// Per runtime slide: `(total_judge_queue_len, track_count,
    /// initial_queue_remaining)`, indexed by runtime slide index.
    slide_totals: Vec<(u64, u64, u64)>,
    fingerprint: String,
    chart_note_ids: Option<HashMap<u64, u64>>,
    chart_slide_positions: Option<HashMap<usize, (u64, usize, usize, usize)>>,
    #[cfg(feature = "backend-rust")]
    sdez: Option<SdezEngine>,
    /// Slide trail progress reported by the SDEZ runtime, keyed by the legacy
    /// runtime arc index the renderer already understands.
    #[cfg(feature = "backend-rust")]
    sdez_progress: Vec<SlideArcProgress>,
}

fn ensure_runtime() {
    session::ensure_runtime().expect("lnmai-core runtime must initialize");
}

/// Whether the `MAI2_DEBUG_SLIDE` diagnostic trace is enabled.
pub(crate) fn debug_slide_enabled() -> bool {
    use std::sync::OnceLock;
    static ON: OnceLock<bool> = OnceLock::new();
    *ON.get_or_init(|| std::env::var_os("MAI2_DEBUG_SLIDE").is_some())
}

/// Returns `true` only the first time `key` is seen for `tag` (or after it
/// changes), so diagnostics print on transitions instead of every frame.
pub(crate) fn debug_dedup(tag: impl std::fmt::Display, key: &str) -> bool {
    use std::cell::RefCell;
    use std::collections::HashMap;
    thread_local! {
        static LAST: RefCell<HashMap<String, String>> = RefCell::new(HashMap::new());
    }
    let tag = tag.to_string();
    LAST.with(|last| {
        let mut last = last.borrow_mut();
        if last.get(&tag).map(String::as_str) == Some(key) {
            false
        } else {
            last.insert(tag, key.to_string());
            true
        }
    })
}

impl JudgeEngine {
    /// Create a session and load the chart at `level_index` (`&inote_N`) from
    /// Simai text.
    pub fn load(simai_text: &str, level_index: u32) -> Result<Self, String> {
        ensure_runtime();
        let loaded = Session::<Empty>::create_native()
            .map_err(|e| e.json)?
            .load_chart_text_native(simai_text, level_index)
            .map_err(|e| e.json)?;
        let (slide_bindings, slide_head_timings, slide_totals) = runtime_slide_bindings(&loaded)?;
        let chart_spec = loaded.chart_spec_native().map_err(|e| e.json)?;
        #[cfg(feature = "backend-rust")]
        let sdez = if std::env::var("MAI2_JUDGE_MODE").ok().as_deref() == Some("legacy") {
            None
        } else {
            Some(SdezEngine::load(simai_text, level_index)?)
        };
        Ok(JudgeEngine {
            session: loaded,
            chart_spec,
            last_step_time_us: 0,
            slide_bindings,
            slide_head_timings,
            slide_totals,
            fingerprint: AutoplayPlan::fingerprint(simai_text, level_index),
            chart_note_ids: None,
            chart_slide_positions: None,
            #[cfg(feature = "backend-rust")]
            sdez,
            #[cfg(feature = "backend-rust")]
            sdez_progress: Vec::new(),
        })
    }

    /// Bind a recompiled editor chart without changing its stable note IDs.
    pub fn bind_editor_chart(
        &mut self,
        mut note_ids: HashMap<u64, u64>,
        slides: HashMap<u64, (u64, usize, usize, usize)>,
    ) -> Result<(), String> {
        let spec = self.chart_spec()?;
        // Normalization can merge identical trails, but must not drop any
        // emitted source object or introduce IDs the editor cannot resolve.
        let source_count = spec.taps.len()
            + spec.holds.len()
            + spec.touches.len()
            + spec.touch_holds.len()
            + spec
                .slides
                .iter()
                .map(|slide| slide.multiple.max(1) as usize)
                .sum::<usize>();
        if source_count != note_ids.len() {
            return Err(format!(
                "edited chart object count mismatch: expected {}, parsed {source_count}",
                note_ids.len()
            ));
        }
        for index in spec
            .taps
            .iter()
            .map(|n| n.note_index)
            .chain(spec.holds.iter().map(|n| n.note_index))
            .chain(spec.touches.iter().map(|n| n.note_index))
            .chain(spec.touch_holds.iter().map(|n| n.note_index))
            .chain(spec.slides.iter().map(|n| n.note_index))
        {
            if !note_ids.contains_key(&index) {
                return Err(format!("unmapped edited note {index}"));
            }
        }
        for head in &spec.slide_heads {
            if let Some(id) = note_ids.get(&head.logical_slide_id).copied() {
                note_ids.insert(head.note_index, id);
            }
        }
        let mut positions = HashMap::new();
        for (note_index, runtime) in &self.slide_bindings {
            let position = slides
                .get(note_index)
                .copied()
                .ok_or_else(|| format!("unmapped edited slide {note_index}"))?;
            positions.insert(*runtime, position);
        }
        self.chart_note_ids = Some(note_ids);
        self.chart_slide_positions = Some(positions);
        Ok(())
    }

    pub fn chart_note_id(&self, note_index: u64) -> Option<u64> {
        match &self.chart_note_ids {
            Some(ids) => ids.get(&note_index).copied(),
            None => Some(note_index),
        }
    }

    pub fn slide_head_note_id(&self, chart: &ChartDoc, note_index: u64) -> Option<u64> {
        if let Some(ids) = &self.chart_note_ids {
            return ids.get(&note_index).copied();
        }
        // Imported stars have editor IDs independent of the lowered head IDs.
        let head = self
            .chart_spec
            .slide_heads
            .iter()
            .find(|head| head.note_index == note_index)?;
        let runtime = self.runtime_slide_index(head.logical_slide_id)?;
        self.slide_position(chart, runtime)
            .map(|position| position.0)
    }

    pub fn slide_position(
        &self,
        chart: &ChartDoc,
        runtime: usize,
    ) -> Option<(u64, usize, usize, usize)> {
        match &self.chart_slide_positions {
            Some(positions) => positions.get(&runtime).copied(),
            None => chart_slide_position(chart, runtime),
        }
    }

    /// `(total_judge_queue_len, track_count, initial_queue_remaining)` for a
    /// runtime slide index.
    pub fn slide_queue_total(&self, runtime_slide_index: usize) -> Option<(u64, u64, u64)> {
        self.slide_totals.get(runtime_slide_index).copied()
    }

    /// Diagnostic (`MAI2_DEBUG_SLIDE`): dump the runtime slide bindings.
    pub fn debug_dump_slide_bindings(&self) {
        for (runtime, meta) in self.slide_totals.iter().enumerate() {
            let note_index = self
                .slide_bindings
                .iter()
                .find(|(_, rt)| **rt == runtime)
                .map(|(note, _)| *note);
            eprintln!(
                "[slide/bindings] rt={runtime} note_index={note_index:?} \
                 total_judge_queue={} track_count={} initial_remaining={}",
                meta.0, meta.1, meta.2
            );
        }
    }

    /// Advance the runtime by one frame with the given input events at
    /// `current_secs` (song time in seconds, converted to µs ticks).
    pub fn step(
        &mut self,
        current_secs: f32,
        events: Vec<TimedInputEvent>,
    ) -> Result<RuntimeStepLightResult, String> {
        self.step_us((current_secs.max(0.0) as f64 * 1e6).round() as i64, events)
    }

    /// Event timestamps must never round-trip through f32 seconds: a clock a
    /// microsecond before its input causes the core to discard that input.
    pub fn step_us(
        &mut self,
        requested_time_us: i64,
        mut events: Vec<TimedInputEvent>,
    ) -> Result<RuntimeStepLightResult, String> {
        let current_time_us = requested_time_us.max(self.last_step_time_us);
        // A stalled frame can leave autoplay events behind the core clock.
        // Keep those events in the current zero-duration frame instead of
        // asking the core to move backwards and dropping the whole step.
        for event in &mut events {
            if timed_input_tp(event) < self.last_step_time_us {
                *event = retime_input_event(event, self.last_step_time_us);
            }
        }
        sort_timed_input_events(&mut events);
        #[cfg(feature = "backend-rust")]
        if let Some(sdez) = &mut self.sdez {
            let result = sdez.step(current_time_us, &events)?;
            let progress = sdez.take_slide_progress();
            self.last_step_time_us = result.current_time;
            self.map_sdez_progress(progress);
            return Ok(result);
        }
        if std::env::var_os("MAI2_DEBUG_TOUCHZONE").is_some() && !events.is_empty() {
            eprintln!(
                "[touchzone/core] current_time={} events={events:?}",
                current_time_us
            );
        }
        let batch = TimedInputBatch {
            current_time: current_time_us,
            events,
        };
        let result = self.session.step_native(&batch).map_err(|e| e.json);
        if let Ok(result) = &result {
            self.last_step_time_us = result.current_time;
        }
        result
    }

    pub fn set_autoplay(&mut self, enabled: bool) {
        #[cfg(feature = "backend-rust")]
        if let Some(sdez) = &mut self.sdez {
            sdez.set_autoplay(enabled);
        }
        let _ = enabled;
    }

    pub fn runtime_slide_index(&self, note_index: u64) -> Option<usize> {
        self.slide_bindings.get(&note_index).copied()
    }

    /// True when the SDEZ170 backend owns judgment. SDEZ scores a slide once at
    /// its tail and never emits a separate slide-head note.
    pub fn is_sdez(&self) -> bool {
        #[cfg(feature = "backend-rust")]
        {
            self.sdez.is_some()
        }
        #[cfg(not(feature = "backend-rust"))]
        {
            false
        }
    }

    /// Number of slides in the loaded runtime chart.
    pub fn slide_count(&self) -> usize {
        self.slide_bindings.len()
    }

    /// Trail progress produced by the SDEZ core since the last call.
    #[cfg(feature = "backend-rust")]
    pub fn take_slide_progress(&mut self) -> Vec<SlideArcProgress> {
        std::mem::take(&mut self.sdez_progress)
    }

    #[cfg(feature = "backend-rust")]
    fn map_sdez_progress(&mut self, progress: Vec<SdezSlideProgress>) {
        let mut mapped = Vec::new();
        for slide in progress {
            let Some(runtime) = self.slide_bindings.get(&slide.note_index).copied() else {
                continue;
            };
            if slide.is_wifi {
                for (track, frac) in slide.tracks.iter().enumerate() {
                    mapped.push(SlideArcProgress {
                        runtime_slide_index: runtime,
                        track_index: Some(track as u64),
                        frac: frac.clamp(0.0, 1.0),
                        hidden_until_bar: None,
                        // SDEZ reports a real per-track fraction, not the
                        // legacy shared cursor.
                        shared_frac: None,
                    });
                }
            } else {
                mapped.push(SlideArcProgress {
                    runtime_slide_index: runtime,
                    track_index: None,
                    frac: slide.progress.clamp(0.0, 1.0),
                    hidden_until_bar: None,
                    shared_frac: None,
                });
            }
        }
        self.sdez_progress = mapped;
    }

    /// Core slide head timing (µs) at `runtime_slide_index`.
    pub fn slide_head_timing(&self, runtime_slide_index: usize) -> Option<i64> {
        self.slide_head_timings.get(runtime_slide_index).copied()
    }

    /// Build lnmai-core's default replay tactic (autoplay events) for the
    /// loaded chart. The events carry microsecond timestamps matching runtime
    /// input, so the player can feed them frame by frame.
    /// The lowered chart (per runtime slide arc: timings + ordered sensor-area
    /// queues with arrow progress). Used to drive a custom autoplay tactic.
    pub fn chart_spec(&self) -> Result<ChartSpec, String> {
        Ok(self.chart_spec.clone())
    }

    pub fn judgment_metadata(&self, chart: &ChartDoc) -> crate::player::judge_windows::Metadata {
        crate::player::judge_windows::Metadata::from_spec(
            &self.chart_spec,
            |index| self.chart_note_id(index),
            |index| {
                self.runtime_slide_index(index)
                    .and_then(|runtime| self.slide_position(chart, runtime))
                    .map(|(id, sub, _, _)| (id, sub))
            },
        )
    }

    pub fn seek(&mut self, seconds: f32) -> Result<SeekResult, String> {
        self.seek_with_events(seconds, &[], false)
    }

    pub fn seek_with_events(
        &mut self,
        seconds: f32,
        events: &[TimedInputEvent],
        keep_held: bool,
    ) -> Result<SeekResult, String> {
        if !seconds.is_finite() {
            return Err("invalid seek time".into());
        }
        #[cfg(feature = "backend-rust")]
        if let Some(sdez) = &mut self.sdez {
            let result = sdez.seek((seconds.max(0.0) * 1e6) as i64, events, keep_held)?;
            let progress = sdez.take_slide_progress();
            self.last_step_time_us = result.current_time;
            self.map_sdez_progress(progress);
            return Ok(result);
        }
        let result = self
            .session
            .seek_with_events((seconds.max(0.0) * 1e6) as i64, events, keep_held)
            .map_err(|e| e.json);
        if let Ok(result) = &result {
            self.last_step_time_us = result.current_time;
        }
        result
    }

    pub fn autoplay_plan(&self) -> Result<AutoplayPlan, String> {
        let mut plan = self.session.autoplay_plan().map_err(|e| e.json)?;
        plan.chart_fingerprint = self.fingerprint.clone();
        Ok(plan)
    }

    pub fn default_tactic(&self) -> Result<Vec<TimedInputEvent>, String> {
        #[cfg(feature = "backend-rust")]
        if let Some(sdez) = &self.sdez {
            sdez.enable_autoplay();
        }
        Ok(self.autoplay_plan()?.events())
    }

    /// Consumed fraction (0..1) of each runtime slide arc, from a frame's render
    /// commands.
    ///
    /// lnmai reports slide progress per **runtime arc** (one `noteIndex` per arc
    /// of a continuous chain), in its own judge-queue units. The caller slots
    /// each arc's fraction into that arc's segment range of the chart sub-slide,
    /// so a later arc can never be hidden by an earlier arc's progress.
    pub fn slide_progress_updates(&self, commands: &[RenderCommand]) -> Vec<SlideArcProgress> {
        // Keyed by `(runtime arc, track)`: wifi's three tracks report progress
        // independently and must not be merged into one cutoff.
        let mut by_arc: HashMap<(usize, Option<u64>), SlideArcProgress> = HashMap::new();
        for command in commands {
            let Some(update) = self.slide_progress_update(command) else {
                continue;
            };
            let entry = by_arc
                .entry((update.runtime_slide_index, update.track_index))
                .or_insert(SlideArcProgress {
                    runtime_slide_index: update.runtime_slide_index,
                    track_index: update.track_index,
                    frac: 0.0,
                    hidden_until_bar: None,
                    shared_frac: None,
                });
            entry.frac = entry.frac.max(update.frac);
            entry.shared_frac = match (entry.shared_frac, update.shared_frac) {
                (Some(a), Some(b)) => Some(a.max(b)),
                (a, b) => a.or(b),
            };
            entry.hidden_until_bar = match (entry.hidden_until_bar, update.hidden_until_bar) {
                (Some(a), Some(b)) => Some(a.max(b)),
                (a, b) => a.or(b),
            };
        }

        let mut updates: Vec<_> = by_arc.into_values().collect();
        updates.sort_by_key(|update| (update.runtime_slide_index, update.track_index));
        updates
    }

    fn slide_progress_update(&self, command: &RenderCommand) -> Option<SlideArcProgress> {
        let (note_index, track_index, frac, hidden_until_bar) = match command {
            // Per-arc judge progress is the authoritative signal: `remaining`
            // counts down the arc's own judge queue (0 ⇒ arc finished).
            RenderCommand::UpdateSlideProgress {
                note_index,
                remaining,
            } => (
                *note_index,
                None,
                self.frac_from_remaining(*note_index, *remaining)?,
                None,
            ),
            // Wifi reports one of these per track; keep the track identity. Its
            // `remaining` is in per-track units, so it is only a fallback — the
            // authoritative cutoff is `HideSlideTrackBars` below.
            RenderCommand::UpdateSlideTrackProgress {
                note_index,
                track_index,
                remaining,
            } => (
                *note_index,
                Some(*track_index),
                if self.is_wifi(*note_index)? { 0.0 }
                    else { self.frac_from_remaining(*note_index, *remaining)? },
                None,
            ),
            // A miss hides the whole arc.
            RenderCommand::HideAllSlideBars { note_index } => (*note_index, None, 1.0, None),
            // `HideSlideBars`/`HideSlideTrackBars.endIndex` is in trail-tile
            // units (0..sprite count), which is exactly what the renderer hides.
            RenderCommand::HideSlideBars { note_index, end_index } => (
                *note_index, None, 0.0, Some(*end_index as usize),
            ),
            RenderCommand::HideSlideTrackBars {
                note_index,
                track_index,
                end_index,
            } => (
                *note_index,
                Some(*track_index),
                self.bar_fraction(*note_index, *track_index, *end_index)?,
                Some(*end_index as usize),
            ),
            RenderCommand::ShowJudgeResult { .. } => return None,
        };
        let runtime_slide_index = self.runtime_slide_index(note_index)?;
        let shared_frac = match command {
            RenderCommand::UpdateSlideTrackProgress { remaining, .. } if self.is_wifi(note_index)? =>
                Some(self.frac_from_track_progress(note_index, *remaining)?),
            _ => None,
        };
        Some(SlideArcProgress {
            runtime_slide_index,
            track_index,
            frac: frac.clamp(0.0, 1.0),
            hidden_until_bar,
            shared_frac,
        })
    }

    fn is_wifi(&self, note_index: u64) -> Option<bool> {
        let runtime = self.runtime_slide_index(note_index)?;
        Some(self.chart_spec.slides.get(runtime)?.slide_kind == crate::core::types::RuntimeSlideKind::Wifi)
    }

    fn bar_fraction(&self, note_index: u64, track: u64, value: u64) -> Option<f32> {
        let runtime = self.runtime_slide_index(note_index)?;
        let queue = self.chart_spec.slides.get(runtime)?.judge_queues.get(track as usize)?;
        let total = queue.iter().map(|area| area.arrow_progress_when_finished.max(area.arrow_progress_when_on)).max()?;
        Some(if total == 0 { 0.0 } else { (value as f32 / total as f32).clamp(0.0, 1.0) })
    }

    fn frac_from_remaining(&self, note_index: u64, remaining: u64) -> Option<f32> {
        let runtime = self.runtime_slide_index(note_index)?;
        let (total, _tracks, initial) = self.slide_queue_total(runtime)?;
        // Each runtime arc has its own queue (`initial_queue_remaining`); using
        // the whole-chain `total_judge_queue_len` makes an arc's first update
        // jump several steps. Normalise against the arc's own queue.
        let denom = if initial > 0 { initial } else { total };
        if denom == 0 {
            return None;
        }
        let touched = denom.saturating_sub(remaining).min(denom);
        Some(touched as f32 / denom as f32)
    }

    fn frac_from_track_progress(&self, note_index: u64, value: u64) -> Option<f32> {
        let runtime = self.runtime_slide_index(note_index)?;
        let spec = self.chart_spec.slides.get(runtime)?;
        // WiFi remaining is an increasing bar cursor, not a queue length.
        if spec.slide_kind == crate::core::types::RuntimeSlideKind::Wifi {
            Some((value as f32 / if spec.is_classic { 8.0 } else { 9.0 }).clamp(0.0, 1.0))
        } else { self.frac_from_remaining(note_index, value) }
    }
}

/// Consumed fraction (0..1) of one runtime slide arc.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SlideArcProgress {
    pub runtime_slide_index: usize,
    /// Wifi track this progress belongs to, if the core reported a per-track
    /// update (`UpdateSlideTrackProgress` / `HideSlideTrackBars`).
    pub track_index: Option<u64>,
    /// Consumed fraction from the `*Progress` commands (0..1).
    pub frac: f32,
    /// Explicit trail-bar cutoff from `HideSlideTrackBars` (0..sprite count).
    pub hidden_until_bar: Option<usize>,
    /// WiFi shared cursor, distinct from a branch's explicit hide frontier.
    pub shared_frac: Option<f32>,
}

fn runtime_slide_bindings(
    session: &Session<Loaded>,
) -> Result<(HashMap<u64, usize>, Vec<i64>, Vec<(u64, u64, u64)>), String> {
    let bindings = session.slide_bindings_native().map_err(|e| e.json)?;
    Ok((
        bindings
            .iter()
            .enumerate()
            .map(|(i, b)| (b.note_index, i))
            .collect(),
        bindings.iter().map(|b| b.head_timing).collect(),
        bindings
            .iter()
            .map(|b| {
                (
                    b.total_judge_queue_len,
                    b.track_count,
                    b.initial_queue_remaining,
                )
            })
            .collect(),
    ))
}

trait InputTp {
    fn tp(&self) -> i64;
}
impl InputTp for TimedInputEvent {
    fn tp(&self) -> i64 {
        match self {
            TimedInputEvent::ButtonClick { tp, .. }
            | TimedInputEvent::ButtonHold { tp, .. }
            | TimedInputEvent::SensorClick { tp, .. }
            | TimedInputEvent::SensorHold { tp, .. } => *tp,
        }
    }
}

/// Microsecond timestamp of a core input event.
pub fn timed_input_tp(event: &TimedInputEvent) -> i64 {
    event.tp()
}

/// Adapt lnmai-core's outer-button autoplay events to this player's sensor-only
/// input surface. The pad has no K buttons, so K1..K8 are represented by the
/// corresponding A1..A8 sensor events before the frame is sent back to core.
pub fn normalize_tactic_event(event: TimedInputEvent) -> TimedInputEvent {
    match event {
        TimedInputEvent::ButtonClick { tp, zone } => TimedInputEvent::SensorClick {
            tp,
            area: sensor_area_for_button(zone),
        },
        TimedInputEvent::ButtonHold { tp, zone, is_down } => TimedInputEvent::SensorHold {
            tp,
            area: sensor_area_for_button(zone),
            is_down,
        },
        sensor_event => sensor_event,
    }
}

fn retime_input_event(event: &TimedInputEvent, tp: i64) -> TimedInputEvent {
    match event {
        TimedInputEvent::ButtonClick { zone, .. } => {
            TimedInputEvent::ButtonClick { tp, zone: *zone }
        }
        TimedInputEvent::ButtonHold { zone, is_down, .. } => TimedInputEvent::ButtonHold {
            tp,
            zone: *zone,
            is_down: *is_down,
        },
        TimedInputEvent::SensorClick { area, .. } => {
            TimedInputEvent::SensorClick { tp, area: *area }
        }
        TimedInputEvent::SensorHold { area, is_down, .. } => TimedInputEvent::SensorHold {
            tp,
            area: *area,
            is_down: *is_down,
        },
    }
}

fn sensor_area_for_button(zone: ButtonZone) -> SensorArea {
    match zone {
        ButtonZone::K1 => SensorArea::A1,
        ButtonZone::K2 => SensorArea::A2,
        ButtonZone::K3 => SensorArea::A3,
        ButtonZone::K4 => SensorArea::A4,
        ButtonZone::K5 => SensorArea::A5,
        ButtonZone::K6 => SensorArea::A6,
        ButtonZone::K7 => SensorArea::A7,
        ButtonZone::K8 => SensorArea::A8,
    }
}

/// Advance the engine and apply the resulting core judge/audio commands.
///
/// Normally the frame's inputs are handed to the core in one batch at the frame
/// clock. But a very fast slide (e.g. a long `^` chain at `[8:1]`) packs several
/// arc transitions into a single ~16 ms frame; under one shared clock the core
/// expires the earlier arc before its input is applied (Miss). When a frame's
/// events span more than a few milliseconds they are therefore stepped one at a
/// time at their own timestamps, which keeps the clock aligned with each arc.
///
/// Diagnostic overrides: `MAI2_DEBUG_FORCE_BATCH` treats every frame as normal
/// (batched), `MAI2_DEBUG_FORCE_PEREVENT` steps every frame per event.
/// Play the 击打音 for a hold / touch-hold **head** the instant it is pressed.
///
/// The core reports a hold only at its tail (`stepRegularHoldHead*` emits no
/// event), so the head hit is detected locally from the input events: a press
/// on the hold's lane within its head window plays the note's hit sound (tap
/// for a regular hold, touch for a touch-hold) exactly once.
fn play_hold_head_hits(app: &mut PadPreviewState, events: &[TimedInputEvent]) {
    use crate::player::render::skin::SkinVariant;
    use crate::player::sfx::{self, SfxKind};

    // Scrubbing the timeline must be silent.
    if app.scrubbing {
        return;
    }
    const HEAD_WINDOW_SEC: f32 = 0.10;
    let mut hits: Vec<(u64, SfxKind, bool)> = Vec::new();
    for event in events {
        let (tp, zone, down) = match event {
            TimedInputEvent::SensorClick { tp, area } => (*tp, zone_for_sensor(*area), true),
            TimedInputEvent::SensorHold { tp, area, is_down } => {
                (*tp, zone_for_sensor(*area), *is_down)
            }
            TimedInputEvent::ButtonClick { tp, zone } => (*tp, zone_for_button(*zone), true),
            TimedInputEvent::ButtonHold { tp, zone, is_down } => {
                (*tp, zone_for_button(*zone), *is_down)
            }
        };
        if !down {
            continue;
        }
        let t = tp as f32 / 1e6;
        for note in &app.playback_chart().notes {
            if !matches!(note.note_type, NoteType::Hold | NoteType::TouchHold) {
                continue;
            }
            if note.lane != zone.to_id() || app.hold_head_hits.contains(&note.id) {
                continue;
            }
            if hits.iter().any(|(id, ..)| *id == note.id) {
                continue;
            }
            let ns = crate::app::types::note_secs(note, &app.chart.bpms);
            if (t - ns).abs() > HEAD_WINDOW_SEC {
                continue;
            }
            let kind = if note.is_touch {
                SfxKind::Touch
            } else {
                SfxKind::Tap
            };
            hits.push((note.id, kind, note.is_break));
        }
    }
    // The generic answer cue is timeline-driven in `tick_cues`; the per-kind
    // **hit** sound must obey the 击打音 (`hit_sfx`) toggle, exactly like
    // `play_audio_command`. Otherwise a hold head still beeps with hit SFX off.
    let hit_sfx = crate::app::params::hit_sfx();
    for (id, kind, is_break) in hits {
        if hit_sfx {
            let buf = sfx::select(app, kind, SkinVariant::of_flags(is_break, false), false);
            app.play_sfx(buf);
        }
        app.hold_head_hits.insert(id);
    }
}

pub fn step_judge_engine(app: &mut PadPreviewState) {
    // `no_core`: bypass lnmai-core entirely (pre-lnmai autoplay + star motion).
    if !app.use_core() || app.scrubbing || app.playback_pending || app.audio_start_pending {
        app.engine_events.clear();
        return;
    }
    let now = app.song_time();
    let events = std::mem::take(&mut app.engine_events);
    // The core reports a hold only at its tail, so play the **head** hit here
    // the moment it is actually pressed (a regular hold uses tap.wav, a
    // touch-hold touch.wav).
    play_hold_head_hits(app, &events);
    let results = {
        let engine = app.judge_engine.as_mut().unwrap();
        engine.set_autoplay(app.autoplay);
        step_engine_events(engine, now, events)
    };
    for result in results {
        match result {
            Ok(result) => {
                app.core_score = Some(result.score.clone());
                if let Some(engine) = app.judge_engine.as_mut() {
                    if debug_slide_enabled() {
                        log_lnmai_slide_state(engine, now, &result);
                    }
                    let mut updates = engine.slide_progress_updates(&result.render_commands);
                    updates.extend(engine.take_slide_progress());
                    app.apply_core_slide_progress_updates(&updates);
                }
                handle_engine_result(app, result);
            }
            Err(e) => {
                if !app.status.starts_with("engine") {
                    app.set_status(format!("engine: {e}"));
                }
            }
        }
    }
}

/// Events in one frame that span at most this many microseconds are treated as
/// one batch ("normal frame"). Beyond it the frame contains a sub-frame slide
/// arc and is stepped per event. See [`step_judge_engine`].
const FRAME_INPUT_BATCH_SPAN_US: i64 = 5_000;

/// `MAI2_DEBUG_FORCE_BATCH`: force **every** frame to be treated as a normal
/// (batched) frame, even ones holding a sub-frame arc.
fn force_batch() -> bool {
    use std::sync::OnceLock;
    static ON: OnceLock<bool> = OnceLock::new();
    *ON.get_or_init(|| std::env::var_os("MAI2_DEBUG_FORCE_BATCH").is_some())
}

/// `MAI2_DEBUG_FORCE_PEREVENT`: force **every** frame to be stepped per event,
/// even ordinary ones.
fn force_per_event() -> bool {
    use std::sync::OnceLock;
    static ON: OnceLock<bool> = OnceLock::new();
    *ON.get_or_init(|| std::env::var_os("MAI2_DEBUG_FORCE_PEREVENT").is_some())
}

pub(crate) fn step_engine_events(
    engine: &mut JudgeEngine,
    now: f32,
    mut events: Vec<TimedInputEvent>,
) -> Vec<Result<RuntimeStepLightResult, String>> {
    if events.is_empty() {
        return vec![engine.step(now, Vec::new())];
    }
    sort_timed_input_events(&mut events);
    let per_event = if force_per_event() {
        true
    } else if force_batch() {
        false
    } else {
        let oldest = timed_input_tp(&events[0]);
        let span = timed_input_tp(events.last().unwrap()) - oldest;
        // Batch only what belongs to the current frame. A frame that carried no
        // events for longer than that (a hitch) must still judge each event at
        // its own time: stepping the batch at `now` would judge it late, which
        // costs score for a short hitch and misses the note for a long one.
        span > FRAME_INPUT_BATCH_SPAN_US
            || (now.max(0.0) * 1e6) as i64 - oldest > FRAME_INPUT_BATCH_SPAN_US
    };
    if !per_event {
        return vec![engine.step(now, events)];
    }
    let mut results = Vec::with_capacity(events.len() + 1);
    let mut events = events.into_iter().peekable();
    while let Some(event) = events.next() {
        let at = timed_input_tp(&event);
        let mut batch = vec![event];
        while events.peek().is_some_and(|event| timed_input_tp(event) == at) {
            batch.push(events.next().unwrap());
        }
        results.push(engine.step_us(at, batch));
    }
    results.push(engine.step(now, Vec::new()));
    results
}

/// Diagnostic: dump lnmai-core's slide state — for each runtime arc, its
/// **traveled / total** length (judge-queue units), plus hide commands and slide
/// judge events. Enabled by `MAI2_DEBUG_SLIDE`.
fn log_lnmai_slide_state(engine: &JudgeEngine, now: f32, result: &RuntimeStepLightResult) {
    for command in &result.render_commands {
        let (tag, note_index, line) = match command {
            RenderCommand::UpdateSlideProgress {
                note_index,
                remaining,
            } => {
                let rt = engine.runtime_slide_index(*note_index);
                let total = rt.and_then(|rt| engine.slide_queue_total(rt)).map(|t| t.0);
                let traveled = total.map(|t| t.saturating_sub(*remaining));
                (
                    "progress",
                    *note_index,
                    format!(
                        "star note={note_index} rt={rt:?} traveled={traveled:?}/{total:?} \
                         (remaining={remaining}) UpdateSlideProgress"
                    ),
                )
            }
            RenderCommand::UpdateSlideTrackProgress {
                note_index,
                track_index,
                remaining,
            } => {
                let rt = engine.runtime_slide_index(*note_index);
                let meta = rt.and_then(|rt| engine.slide_queue_total(rt));
                let total = meta.map(|t| t.0);
                let tracks = meta.map(|t| t.1);
                let traveled = total.map(|t| t.saturating_sub(*remaining));
                (
                    "track",
                    *note_index,
                    format!(
                        "star note={note_index} rt={rt:?} traveled={traveled:?}/{total:?} \
                         (remaining={remaining}) UpdateSlideTrackProgress track={track_index}/{tracks:?}"
                    ),
                )
            }
            RenderCommand::HideAllSlideBars { note_index } => {
                let rt = engine.runtime_slide_index(*note_index);
                let total = rt.and_then(|rt| engine.slide_queue_total(rt)).map(|t| t.0);
                (
                    "hideall",
                    *note_index,
                    format!(
                        "star note={note_index} rt={rt:?} traveled={total:?}/{total:?} HideAllSlideBars"
                    ),
                )
            }
            RenderCommand::HideSlideBars {
                note_index,
                end_index,
            } => {
                let rt = engine.runtime_slide_index(*note_index);
                let total = rt.and_then(|rt| engine.slide_queue_total(rt)).map(|t| t.0);
                (
                    "hidebars",
                    *note_index,
                    format!(
                        "star note={note_index} rt={rt:?} hide_end_index={end_index}/{total:?} \
                         HideSlideBars (trail-tile units)"
                    ),
                )
            }
            _ => continue,
        };
        if debug_dedup(format!("lnmai/{tag}/{note_index}"), &line) {
            eprintln!("[slide/lnmai t={now:.3}] {line}");
        }
    }
    for event in &result.events {
        if event.kind == JudgeEventKind::Slide {
            let runtime = engine.runtime_slide_index(event.note_index);
            let line = format!(
                "judge note={} rt={runtime:?} grade={:?}",
                event.note_index, event.grade
            );
            let key = format!("lnmai/judge/{}", event.note_index);
            if debug_dedup(key, &line) {
                eprintln!("[slide/lnmai t={now:.3}] {line}");
            }
        }
    }
}

fn handle_engine_result(app: &mut PadPreviewState, result: RuntimeStepLightResult) {
    let displays =
        collect_judge_result_displays(app.playback_chart(), app.judge_engine.as_ref(), &result);
    for display in displays {
        // Slide heads arrive as Tap/Break events. Only completion uses the
        // shaped Judgement overlay; it must never fall through to tap particles.
        if display.kind == JudgeEventKind::Slide {
            continue;
        }
        app.push_note_judgement(
            display.zone, display.grade, display.is_touch, display.is_break, display.duration,
        );
        let hold_head = display.kind == JudgeEventKind::Hold
            && display.phase == crate::core::types::JudgePhase::Head;
        if display.kind == JudgeEventKind::Hold && !hold_head
            && let Some(id) = display.note_id
        {
            app.stop_hold_fx(id);
        }
        if display.is_hit {
            let effect = if hold_head {
                HitEffect::Hold
            } else if display.is_break {
                HitEffect::Break
            } else if display.kind == JudgeEventKind::Hold {
                HitEffect::HoldRelease
            } else if display.is_touch {
                HitEffect::Touch
            } else if display.is_ex {
                HitEffect::ExTap
            } else {
                HitEffect::Tap
            };
            let duration = hold_head.then(|| {
                display.note_id
                    .and_then(|id| chart_note(app.playback_chart(), id))
                    .map(|note| {
                        (crate::app::types::hold_tail_time(note, &app.chart.bpms) - app.song_time()).max(0.0)
                    })
                    .unwrap_or(0.0)
            });
            app.push_note_hit_fx(
                display.zone, display.grade, effect, display.is_touch, duration, display.note_id,
            );
            if display.is_hanabi && !hold_head {
                app.push_hanabi_feedback(display.zone, display.grade, display.is_touch, display.note_id);
            }
        }
    }
    // Record slide judgments so the renderer can show the `slideok` overlay.
    for fx in collect_slide_judge_fx(app.playback_chart(), app.judge_engine.as_ref(), &result) {
        app.record_slide_judge(fx.note_id, fx.slide_idx, fx.grade);
    }
    // Completed single-hit notes disappear on judgment, not after a timer.
    let hidden = judged_single_hit_notes(app.playback_chart(), app.judge_engine.as_ref(), &result);
    app.hidden_notes.extend(hidden);
    for command in &result.audio_commands {
        play_audio_command(app, command);
    }
}

fn judged_single_hit_notes(
    chart: &ChartDoc,
    engine: Option<&JudgeEngine>,
    result: &RuntimeStepLightResult,
) -> Vec<u64> {
    result
        .events
        .iter()
        .filter(|event| {
            matches!(
                event.kind,
                JudgeEventKind::Touch | JudgeEventKind::Tap | JudgeEventKind::Break
            )
        })
        .filter_map(|event| {
            let index = match engine {
                Some(engine) => engine.chart_note_id(event.note_index)?,
                None => event.note_index,
            };
            chart_note(chart, index)
        })
        .filter(|note| matches!(note.note_type, NoteType::Touch | NoteType::Tap))
        .map(|note| note.id)
        .collect()
}

/// A slide judgment mapped onto a chart sub-slide, for the `slideok` overlay.
struct SlideJudgeFxResult {
    note_id: u64,
    slide_idx: usize,
    grade: crate::player::state::SlideJudgeGrade,
}

/// Collect lnmai-core's slide judgments and map each runtime note onto the
/// chart's `(note_id, slide_idx)` key used by the renderer's per-sub-slide fx.
fn collect_slide_judge_fx(
    chart: &ChartDoc,
    engine: Option<&JudgeEngine>,
    result: &RuntimeStepLightResult,
) -> Vec<SlideJudgeFxResult> {
    use crate::player::state::SlideJudgeGrade;

    let mut out = Vec::new();
    let mut seen: HashSet<(u64, usize)> = HashSet::new();
    let mut push = |note_index: u64, grade: JudgeGrade| {
        let Some(engine) = engine else { return };
        let Some(runtime_slide_index) = engine.runtime_slide_index(note_index) else {
            return;
        };
        let Some((note_id, slide_idx, _, _)) = engine.slide_position(chart, runtime_slide_index)
        else {
            return;
        };
        if seen.insert((note_id, slide_idx)) {
            out.push(SlideJudgeFxResult {
                note_id,
                slide_idx,
                grade: SlideJudgeGrade::from_grade(grade),
            });
        }
    };

    for command in &result.render_commands {
        if let RenderCommand::ShowJudgeResult {
            kind: JudgeEventKind::Slide,
            grade,
            note_index,
            ..
        } = command
        {
            push(*note_index, *grade);
        }
    }
    for event in &result.events {
        if event.kind == JudgeEventKind::Slide {
            push(event.note_index, event.grade);
        }
    }
    out
}

#[derive(Debug, Clone, PartialEq)]
struct JudgeResultDisplay {
    zone: PadZone,
    grade: FeedbackGrade,
    duration: f64,
    kind: JudgeEventKind,
    is_break: bool,
    is_touch: bool,
    is_ex: bool,
    is_hanabi: bool,
    note_id: Option<u64>,
    phase: crate::core::types::JudgePhase,
    /// True when the note was actually hit (not a miss / too-fast).
    is_hit: bool,
}

/// Map lnmai-core's render/event results onto (zone, label) feedbacks.
fn collect_judge_result_displays(
    chart: &ChartDoc,
    engine: Option<&JudgeEngine>,
    result: &RuntimeStepLightResult,
) -> Vec<JudgeResultDisplay> {
    let mut displays = Vec::new();
    for event in &result.events {
        if let Some(display) = make_judge_result_display(
            chart, engine, std::slice::from_ref(event), event.note_index, event.kind, event.grade,
        ) {
            displays.push(display);
        }
    }
    for command in &result.render_commands {
        if let RenderCommand::ShowJudgeResult {
            kind,
            grade,
            note_index,
            ..
        } = command
        {
            if result.events.iter().any(|event| event.note_index == *note_index && event.kind == *kind) {
                continue;
            }
            if let Some(display) =
                make_judge_result_display(chart, engine, &result.events, *note_index, *kind, *grade)
            {
                displays.push(display);
            }
        }
    }

    displays
}

fn make_judge_result_display(
    chart: &ChartDoc,
    engine: Option<&JudgeEngine>,
    events: &[JudgeEvent],
    note_index: u64,
    kind: JudgeEventKind,
    grade: JudgeGrade,
) -> Option<JudgeResultDisplay> {
    let zone = judge_result_zone(chart, engine, events, note_index, kind)?;
    let duration = if grade.is_miss_or_too_fast() {
        0.24
    } else {
        0.3
    };
    let event = events
        .iter()
        .find(|e| e.note_index == note_index && e.kind == kind);
    let slide_key = engine.and_then(|engine| {
        engine.runtime_slide_index(note_index)
            .and_then(|runtime| engine.slide_position(chart, runtime))
    });
    let chart_id = if kind == JudgeEventKind::Slide {
        slide_key.map(|(id, ..)| id)
    } else {
        engine.and_then(|engine| {
            engine.slide_head_note_id(chart, note_index)
                .or_else(|| engine.chart_note_id(note_index))
        })
    }.unwrap_or(note_index);
    let note = chart_note(chart, chart_id);
    let is_touch = kind == JudgeEventKind::Touch
        || (kind != JudgeEventKind::Slide && note.is_some_and(crate::app::types::note_is_touch));
    let is_break = event.is_some_and(|e| e.is_break) || {
        if kind == JudgeEventKind::Slide {
            slide_key.and_then(|(_, index, ..)| note.and_then(|n| n.slide.get(index)))
                .is_some_and(|slide| slide.slide_is_break)
        } else {
            note.is_some_and(|n| n.is_break)
        }
    };
    Some(JudgeResultDisplay {
        zone,
        grade: grade.into(),
        duration,
        kind,
        is_break,
        is_touch,
        is_ex: event.is_some_and(|e| e.is_ex) || note.is_some_and(|n| n.is_ex),
        is_hanabi: is_touch && note.is_some_and(|n| n.is_hanabi),
        note_id: note.map(|n| n.id),
        phase: event.map(|e| e.phase).unwrap_or(crate::core::types::JudgePhase::Tail),
        is_hit: !grade.is_miss_or_too_fast(),
    })
}

fn judge_result_zone(
    chart: &ChartDoc,
    engine: Option<&JudgeEngine>,
    events: &[JudgeEvent],
    note_index: u64,
    kind: JudgeEventKind,
) -> Option<PadZone> {
    if kind == JudgeEventKind::Slide {
        slide_tail_zone_for_runtime_note(chart, engine, note_index)
            .or_else(|| event_position_zone(events, note_index, kind))
    } else {
        event_position_zone(events, note_index, kind).or_else(|| {
            let index = match engine {
                Some(engine) => engine.chart_note_id(note_index)?,
                None => note_index,
            };
            chart_note_head_zone(chart, index)
        })
    }
}

fn judge_sfx_allowed(grade: JudgeGrade) -> bool {
    !grade.is_miss_or_too_fast()
}

fn event_position_zone(
    events: &[JudgeEvent],
    note_index: u64,
    kind: JudgeEventKind,
) -> Option<PadZone> {
    let ev = events
        .iter()
        .find(|ev| ev.note_index == note_index && ev.kind == kind)?;
    if let Some(button) = ev.position.button {
        Some(zone_for_button(button))
    } else {
        ev.position.sensor.map(zone_for_sensor)
    }
}

fn slide_tail_zone_for_runtime_note(
    chart: &ChartDoc,
    engine: Option<&JudgeEngine>,
    note_index: u64,
) -> Option<PadZone> {
    let engine = engine?;
    let runtime_slide_index = engine.runtime_slide_index(note_index)?;
    let (note_id, slide_idx, _, _) = engine.slide_position(chart, runtime_slide_index)?;
    chart
        .notes
        .iter()
        .find(|note| note.id == note_id)
        .and_then(|note| note.slide.get(slide_idx))
        .and_then(|slide| slide.segments.last())
        .and_then(|segment| segment.points.last())
        .map(|point| point.zone)
}

fn chart_slide_tail_zone(chart: &ChartDoc, runtime_slide_index: usize) -> Option<PadZone> {
    chart_slide_key(chart, runtime_slide_index).and_then(|(note_id, slide_idx)| {
        chart
            .notes
            .iter()
            .find(|note| note.id == note_id)
            .and_then(|note| note.slide.get(slide_idx))
            .and_then(|slide| slide.segments.last())
            .and_then(|segment| segment.points.last())
            .map(|point| point.zone)
    })
}

fn chart_note_head_zone(chart: &ChartDoc, note_index: u64) -> Option<PadZone> {
    chart_note(chart, note_index).map(|note| PadZone::from(note.lane))
}

/// Resolve the chart note for a lnmai `noteIndex` (the runtime index is the
/// chart note id, or a 1-based position only when that note has no id).
fn chart_note<'a>(chart: &'a ChartDoc, note_index: u64) -> Option<&'a crate::app::types::Note> {
    if note_index == 0 {
        return None;
    }
    chart
        .notes
        .iter()
        .find(|note| note.id == note_index)
        .or_else(|| {
            usize::try_from(note_index)
                .ok()
                .and_then(|index| chart.notes.get(index - 1))
                .filter(|note| note.id == 0)
        })
}

/// Map a runtime slide index onto the chart's `(note_id, slide_idx)`.
///
/// lnmai-core splits a continuous multi-arc slide into one runtime slide per
/// arc, so each chart sub-slide consumes `slide.runtime_parts` runtime indices.
pub fn chart_slide_key(chart: &ChartDoc, runtime_slide_index: usize) -> Option<(u64, usize)> {
    chart_slide_position(chart, runtime_slide_index)
        .map(|(note_id, slide_idx, _, _)| (note_id, slide_idx))
}

/// Like [`chart_slide_key`] but also resolves which **segment** (runtime arc)
/// of the chart sub-slide `runtime_slide_index` is, and how many segments the
/// sub-slide has: `(note_id, slide_idx, segment_idx, segment_count)`.
pub fn chart_slide_position(
    chart: &ChartDoc,
    runtime_slide_index: usize,
) -> Option<(u64, usize, usize, usize)> {
    let mut current = 0;
    chart
        .notes
        .iter()
        .filter(|note| matches!(note.note_type, NoteType::Slide))
        .find_map(|note| {
            for (slide_idx, slide) in note.slide.iter().enumerate() {
                let parts = slide.runtime_parts.max(1);
                if runtime_slide_index < current + parts {
                    return Some((note.id, slide_idx, runtime_slide_index - current, parts));
                }
                current += parts;
            }
            None
        })
}

fn play_audio_command(app: &mut PadPreviewState, command: &AudioCommand) {
    if !app.audio_enabled || app.scrubbing {
        return;
    }
    use crate::player::render::skin::SkinVariant;
    use crate::player::sfx::{self, SfxKind};

    // The per-kind hit SFX comes from actual hits (answer cue is timeline-driven
    // in `state::tick_cues`).
    let mut hit: Option<&crate::app::audio::SfxBuffer> = None;
    match command {
        AudioCommand::PlayTouchHoldBody { .. } => {
            hit = app.sfx_hold.as_ref();
        }
        AudioCommand::PlayJudgeSfx {
            kind,
            grade,
            is_break,
            note_index,
            ..
        } => {
            if judge_sfx_allowed(*grade) {
                let sfx_kind = match kind {
                    JudgeEventKind::Tap => SfxKind::Tap,
                    JudgeEventKind::Touch => SfxKind::Touch,
                    // lnmai reports touch-holds as `Hold`; they use the touch
                    // sound, regular holds the tap sound.
                    JudgeEventKind::Hold => {
                        let id = match app.judge_engine.as_ref() {
                            Some(engine) => engine.chart_note_id(*note_index),
                            None => Some(*note_index),
                        };
                        if id
                            .and_then(|id| chart_note(app.playback_chart(), id))
                            .is_some_and(|n| n.is_touch)
                        {
                            SfxKind::Touch
                        } else {
                            SfxKind::Tap
                        }
                    }
                    JudgeEventKind::Slide => SfxKind::SlideJudge,
                    JudgeEventKind::Break => SfxKind::Tap,
                };
                let is_break = *is_break || matches!(kind, JudgeEventKind::Break);
                hit = sfx::select(app, sfx_kind, SkinVariant::of_flags(is_break, false), false);
            }
        }
        AudioCommand::PlaySlideCue { is_break, .. } => {
            // The core explicitly requested the slide cue; do not synthesize
            // any local progress or deduplicate this command.
            hit = sfx::select(
                app,
                SfxKind::SlideCue,
                SkinVariant::of_flags(*is_break, false),
                false,
            );
        }
    }

    if crate::app::params::hit_sfx() {
        app.play_sfx(hit);
    }
}

