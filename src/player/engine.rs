/// A loaded lnmai-core (FFI) runtime session.
pub struct JudgeEngine {
    session: Session<Loaded>,
    slide_bindings: HashMap<u64, RuntimeSlideBinding>,
}

#[derive(Debug, Clone, Copy)]
struct RuntimeSlideBinding {
    runtime_slide_index: usize,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SlideProgressUpdate {
    pub runtime_slide_index: usize,
    pub hidden_until_bar: usize,
}

fn ensure_runtime() {
    session::ensure_runtime().expect("lnmai-core runtime must initialize");
}

impl JudgeEngine {
    /// Create a session and load the chart at `level_index` from Simai text.
    pub fn load(simai_text: &str, level_index: u32) -> Result<Self, String> {
        ensure_runtime();
        let empty = Session::<Empty>::create().map_err(|e| e.json)?;
        let (loaded, _envelope) = empty
            .load_chart_text(simai_text, level_index)
            .map_err(|e| e.json)?;
        let slide_bindings = runtime_slide_bindings(&loaded)?;
        Ok(JudgeEngine {
            session: loaded,
            slide_bindings,
        })
    }

    /// Advance the runtime by one frame with the given input events at
    /// `current_secs` (song time in seconds, converted to µs ticks). Returns
    /// the complete light-frame result so the player can render core commands.
    pub fn step(
        &mut self,
        current_secs: f32,
        mut events: Vec<TimedInputEvent>,
    ) -> Result<RuntimeStepLightResult, String> {
        events.sort_by_key(|e| e.tp());
        let batch = TimedInputBatch {
            current_time: (current_secs.max(0.0) * 1e6) as i64,
            events,
        };
        let t_ser = Instant::now();
        let json = serde_json::to_string(&batch).map_err(|e| e.to_string())?;
        let ser_ns = t_ser.elapsed();

        let (envelope, ffi_timings) = self
            .session
            .advance_frame_light_timed(&json)
            .map_err(|e| e.json)?;

        let t_de = Instant::now();
        let result = envelope
            .decode_result::<RuntimeStepLightResult>()
            .map_err(|e| e.to_string())?;
        let de_ns = t_de.elapsed();

        crate::perf::record("engine.serialize", ser_ns);
        crate::perf::record(
            "engine.ffi.mk_string",
            std::time::Duration::from_nanos(ffi_timings.mk_string_ns),
        );
        crate::perf::record(
            "engine.ffi.lean",
            std::time::Duration::from_nanos(ffi_timings.ffi_ns),
        );
        crate::perf::record(
            "engine.ffi.into_string",
            std::time::Duration::from_nanos(ffi_timings.into_string_ns),
        );
        crate::perf::record("engine.deserialize", de_ns);

        Ok(result)
    }

    pub fn runtime_slide_index(&self, note_index: u64) -> Option<usize> {
        self.slide_bindings
            .get(&note_index)
            .map(|binding| binding.runtime_slide_index)
    }

    /// Build lnmai-core's default replay tactic (autoplay events) for the
    /// loaded chart. The events carry the same `tp` microsecond timestamps as
    /// runtime input, so the player can feed them frame by frame.
    pub fn default_tactic(&self) -> Result<Vec<TimedInputEvent>, String> {
        let envelope = self.session.get_lowered_chart_json().map_err(|e| e.json)?;
        let chart: ChartSpec = envelope
            .decode_result()
            .map_err(|e| format!("invalid lowered chart json: {e}"))?;
        lnmai_core::api::default_tactic_from_chart(&chart)
            .map(|tactic| tactic.events)
            .map_err(|e| e.json)
    }

    pub fn slide_progress_updates(&self, commands: &[RenderCommand]) -> Vec<SlideProgressUpdate> {
        let mut by_slide: HashMap<usize, usize> = HashMap::new();
        for command in commands {
            let Some(update) = self.slide_progress_update(command) else {
                continue;
            };
            by_slide
                .entry(update.runtime_slide_index)
                .and_modify(|hidden| *hidden = (*hidden).max(update.hidden_until_bar))
                .or_insert(update.hidden_until_bar);
        }

        let mut updates: Vec<_> = by_slide
            .into_iter()
            .map(
                |(runtime_slide_index, hidden_until_bar)| SlideProgressUpdate {
                    runtime_slide_index,
                    hidden_until_bar,
                },
            )
            .collect();
        updates.sort_by_key(|update| update.runtime_slide_index);
        updates
    }

    fn slide_progress_update(&self, command: &RenderCommand) -> Option<SlideProgressUpdate> {
        let (note_index, hidden_until_bar) = match command {
            RenderCommand::UpdateSlideProgress { .. } => return None,
            RenderCommand::UpdateSlideTrackProgress { .. } => return None,
            RenderCommand::HideAllSlideBars { note_index } => (*note_index, usize::MAX),
            RenderCommand::HideSlideBars {
                note_index,
                end_index,
            } => (*note_index, *end_index as usize),
            RenderCommand::HideSlideTrackBars { .. } => return None,
            RenderCommand::ShowJudgeResult { .. } => return None,
        };
        let binding = self.slide_bindings.get(&note_index)?;
        Some(SlideProgressUpdate {
            runtime_slide_index: binding.runtime_slide_index,
            hidden_until_bar,
        })
    }
}

fn runtime_slide_bindings(
    session: &Session<Loaded>,
) -> Result<HashMap<u64, RuntimeSlideBinding>, String> {
    let envelope = session.get_state_json().map_err(|e| e.json)?;
    let state = envelope
        .decode_result::<GameState>()
        .map_err(|e| format!("invalid engine state json: {e}"))?;
    Ok(state
        .slides
        .iter()
        .enumerate()
        .map(|(runtime_slide_index, slide)| {
            (
                slide.params.note_index,
                RuntimeSlideBinding {
                    runtime_slide_index,
                },
            )
        })
        .collect())
}

trait InputTp {
    fn tp(&self) -> i64;
}
impl InputTp for TimedInputEvent {
    fn tp(&self) -> i64 {
        match self {
            TimedInputEvent::ButtonClick { tp, .. }
            | TimedInputEvent::ButtonHold { tp, .. }
            | TimedInputEvent::SensorClick { tp, .. }
            | TimedInputEvent::SensorHold { tp, .. } => *tp,
        }
    }
}

